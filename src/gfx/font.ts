export const FONT_CHARS = Object.keys(G).join('');
export const FONT_W = 6;
export const FONT_H = 8;

export function createFont(scene: Phaser.Scene): void {
  const chars = FONT_CHARS;
  const perRow = 16;
  const rows = Math.ceil(chars.length / perRow);
  const [c, ctx] = makeCanvas(perRow * FONT_W, rows * FONT_H);
  ctx.fillStyle = '#ffffff';
  [...chars].forEach((ch, i) => {
    const bits = G[ch].padEnd(35, '.');
    const ox = (i % perRow) * FONT_W;
    const oy = Math.floor(i / perRow) * FONT_H;
    for (let y = 0; y < 7; y++) {
      for (let x = 0; x < 5; x++) {
        if (bits[y * 5 + x] === '#') ctx.fillRect(ox + x, oy + y, 1, 1);
      }
    }
  });
  registerCanvas(scene, 'font-img', c);
  const config: Phaser.Types.GameObjects.BitmapText.RetroFontConfig = {
    image: 'font-img',
    width: FONT_W,
    height: FONT_H,
    chars,
    charsPerRow: perRow,
    'offset.x': 0,
    'offset.y': 0,
    'spacing.x': 0,
    'spacing.y': 0,
    lineSpacing: 2,
  };
  scene.cache.bitmapFont.add('font', Phaser.GameObjects.RetroFont.Parse(scene, config));
}

/** Bringt Text in den Zeichensatz des Fonts (Großbuchstaben, ß → SS). */
export function normalizeText(s: string): string {
  return s
    .toUpperCase()
    .replace(/ẞ/g, 'SS')
    .replace(/ß/g, 'SS')
    .replace(/[^\n]/g, (ch) => (FONT_CHARS.includes(ch) ? ch : ch === '–' ? '–' : ' '));
}
